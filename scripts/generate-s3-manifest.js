#!/usr/bin/env node
/**
 * generate-s3-manifest.js
 *
 * Scans public/uploads/institutions/ and produces:
 *   1. s3-manifest.json  — structured list of every file → its S3 destination
 *   2. s3-upload.sh      — ready-to-run AWS CLI script (one aws s3 cp per file)
 *   3. Console summary   — per-institution table
 *
 * Usage:
 *   node scripts/generate-s3-manifest.js --bucket my-bucket-name [--prefix institutions]
 *
 * Then either:
 *   bash s3-upload.sh                      (uses AWS CLI, respects ~/.aws/credentials)
 *   aws s3 sync public/uploads/institutions s3://my-bucket/institutions  (bulk alternative)
 */

const fs = require('fs');
const path = require('path');

// ─── Config ──────────────────────────────────────────────────────────────────
const args = process.argv.slice(2);
const bucket = argValue(args, '--bucket') || 'art-explore-db-images';
const prefix = argValue(args, '--prefix') || 'institutions';
const source = path.resolve(__dirname, '..', 'public', 'uploads', 'institutions');
const outDir = path.resolve(__dirname, '..'); // project root

// ─── Main ─────────────────────────────────────────────────────────────────────
if (!fs.existsSync(source)) {
  console.error(`❌  Source folder not found: ${source}`);
  console.error('    Run the download script first.');
  process.exit(1);
}

const institutionDirs = fs
  .readdirSync(source, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort();

if (institutionDirs.length === 0) {
  console.error('❌  No institution folders found inside', source);
  process.exit(1);
}

const manifest = [];
const cliLines = [
  '#!/usr/bin/env bash',
  '# Auto-generated by generate-s3-manifest.js',
  `# Uploads institution images to s3://${bucket}/${prefix}/`,
  '# Run:  bash s3-upload.sh',
  '',
  'set -euo pipefail',
  '',
  `BUCKET="${bucket}"`,
  `PREFIX="${prefix}"`,
  '',
];

let totalFiles = 0;
const rows = []; // for console table

for (const slug of institutionDirs) {
  const slugDir = path.join(source, slug);
  const files = fs.readdirSync(slugDir).filter((f) => /\.(jpg|jpeg|png|webp|gif|svg)$/i.test(f));

  rows.push({ slug, count: files.length });

  if (files.length === 0) {
    cliLines.push(`# ⚠️  ${slug} — no image files found, skipping`);
    cliLines.push('');
    continue;
  }

  cliLines.push(`# ── ${slug} (${files.length} file${files.length !== 1 ? 's' : ''}) ──`);

  for (const file of files) {
    const localPath = path.join(slugDir, file);
    const s3Key = `${prefix}/${slug}/${file}`;
    const s3Uri = `s3://${bucket}/${s3Key}`;

    // Guess content-type
    const ext = path.extname(file).toLowerCase();
    const mime =
      {
        '.jpg': 'image/jpeg',
        '.jpeg': 'image/jpeg',
        '.png': 'image/png',
        '.webp': 'image/webp',
        '.gif': 'image/gif',
        '.svg': 'image/svg+xml',
      }[ext] || 'image/jpeg';

    manifest.push({ slug, file, localPath, s3Key, s3Uri, contentType: mime });

    cliLines.push(`aws s3 cp "${localPath}" "${s3Uri}" --content-type "${mime}" --acl public-read`);
    totalFiles++;
  }

  cliLines.push('');
}

// Also add the sync-all shortcut at the bottom
cliLines.push('');
cliLines.push('# ── OR: sync the entire folder in one shot ──');
cliLines.push(`# aws s3 sync "${source}" "s3://${bucket}/${prefix}" --acl public-read`);
cliLines.push('');
cliLines.push(`echo "✅  Done — ${totalFiles} files uploaded to s3://${bucket}/${prefix}/"`);

// ─── Write output files ───────────────────────────────────────────────────────
const manifestPath = path.join(outDir, 's3-manifest.json');
const scriptPath = path.join(outDir, 's3-upload.sh');

fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2));
fs.writeFileSync(scriptPath, cliLines.join('\n'));
fs.chmodSync(scriptPath, '755');

// ─── Console summary ──────────────────────────────────────────────────────────
console.log('\n📦  Institution → S3 Manifest\n');
console.log('  Slug'.padEnd(45) + 'Images');
console.log('  ' + '─'.repeat(50));
for (const { slug, count } of rows) {
  const icon = count === 0 ? '⚠️ ' : count >= 2 ? '✅ ' : '🔸 ';
  console.log(`  ${icon} ${slug.padEnd(42)} ${count}`);
}
console.log('  ' + '─'.repeat(50));
console.log(`  Total folders: ${institutionDirs.length}   Total image files: ${totalFiles}\n`);

console.log(`📄  s3-manifest.json  →  ${manifestPath}`);
console.log(`🚀  s3-upload.sh      →  ${scriptPath}`);
console.log('\nNext steps:');
console.log(`  1. Set your bucket name:   edit s3-upload.sh  OR  re-run with --bucket my-bucket`);
console.log(`  2. Ensure AWS CLI is configured:  aws configure`);
console.log(`  3. Run:  bash s3-upload.sh`);
console.log(
  `  4. Or bulk-sync:  aws s3 sync public/uploads/institutions s3://${bucket}/${prefix} --acl public-read\n`,
);

// ─── Helpers ─────────────────────────────────────────────────────────────────
function argValue(args, flag) {
  const i = args.indexOf(flag);
  return i !== -1 && args[i + 1] ? args[i + 1] : null;
}
